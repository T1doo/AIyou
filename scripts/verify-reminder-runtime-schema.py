#!/usr/bin/env python3
"""Exact KSP export/packaged cold contract; never rewrite a schema to make a check pass."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

root = Path(__file__).resolve().parents[1]
export = root / 'core/data/schemas/com.t1doo.aiyou.data.RecordsDatabase/15.json'
asset = root / 'core/data/src/main/assets/reminder-schema-v15.json'
receipt = root / '.local-evidence/reminder-runtime/schema-generation.json'
head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip()

def checkout(path):
    return subprocess.check_output(['git', 'show', f'HEAD:{path.relative_to(root).as_posix()}'], cwd=root)

def digest(raw):
    return hashlib.sha256(raw).hexdigest()

def validate(raw):
    old = json.loads((export.parent / '14.json').read_bytes())['database']
    current = json.loads(raw)['database']
    assert current['version'] == 15 and len(current['entities']) == 22
    assert current['entities'][:-1] == old['entities']
    new = current['entities'][-1]
    assert new['tableName'] == 'reminder_runtime_meta'
    assert [(f['columnName'], f['affinity'], f['notNull']) for f in new['fields']] == [
        ('slot', 'INTEGER', True), ('version', 'INTEGER', True), ('ciphertext', 'BLOB', True)]
    assert new['primaryKey'] == {'autoGenerate': False, 'columnNames': ['slot']}
    assert not new.get('indices', []) and not new.get('foreignKeys', [])
    assert raw == asset.read_bytes()
    for version in range(2, 15):
        path = export.parent / f'{version}.json'
        assert path.read_bytes() == checkout(path), f'Prior Room v{version} changed'

if sys.argv[1:] == ['--capture']:
    raw = export.read_bytes()
    validate(raw)
    assert raw == checkout(export) == checkout(asset), 'v15 must match committed generated bytes'
    receipt.parent.mkdir(parents=True, exist_ok=True)
    receipt.write_text(json.dumps({'head': head, 'sha256': digest(raw), 'bytes': len(raw)}) + '\n')
elif sys.argv[1:] == ['--verify']:
    state = json.loads(receipt.read_text())
    assert state['head'] == head
    raw = export.read_bytes()
    validate(raw)
    assert raw == checkout(export) == checkout(asset)
    assert digest(raw) == state['sha256'] and len(raw) == state['bytes']
    print('REMINDER_RUNTIME_SCHEMA=' + json.dumps(state, separators=(',', ':')))
else:
    raise SystemExit('Usage: verify-reminder-runtime-schema.py --capture|--verify')
